def fmt_acc(mean_val, std_val=None, bold=False, underline=False):
    pct_m = mean_val * 100.0
    if std_val is not None and not np.isnan(std_val):
        pct_s = std_val * 100.0
        val_str = f"{pct_m:.2f} \\pm {pct_s:.2f}"
    else:
        val_str = f"{pct_m:.2f}"
    if bold:
        val_str = f"\\mathbf{{{val_str}}}"
    elif underline:
        val_str = f"\\underline{{{val_str}}}"
    return f"${val_str}$"

